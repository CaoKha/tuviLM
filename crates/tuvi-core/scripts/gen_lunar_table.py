"""Generate src/lunar_table.rs from the Python lunar year data.

Run from the worktree root:

    uv run python crates/tuvi-core/scripts/gen_lunar_table.py

Source: src/refactored/calendar/data/lunar_years.yaml (1800-2199).

Each year packs into one u32:
    bits  0..=11  regular month lengths, bit i set = month i+1 has 30 days
    bits 12..=15  leap month number (0 = no leap month)
    bit  16       leap month has 30 days
    bits 17..=23  Tết offset in days from 1 January of the same solar year
"""

from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "src/refactored/calendar/data/lunar_years.yaml"
OUT = ROOT / "crates/tuvi-core/src/lunar_table.rs"


def pack(year: int, info: dict) -> int:
    lengths = info["regular_month_lengths"]
    assert len(lengths) == 12, year
    word = 0
    for i, length in enumerate(lengths):
        assert length in (29, 30), (year, length)
        word |= (length == 30) << i
    leap = info["leap_month"]
    if leap is not None:
        assert 1 <= leap <= 12, year
        assert info["leap_month_length_days"] in (29, 30), year
        word |= leap << 12
        word |= (info["leap_month_length_days"] == 30) << 16
    else:
        assert info["leap_month_length_days"] is None, year
    offset = info["tet_offset_days"]
    assert 0 <= offset < 128, (year, offset)
    word |= offset << 17
    return word


def main() -> None:
    raw = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    first = raw["supported_years"]["min"]
    last = raw["supported_years"]["max"]
    years = raw["years"]
    words = [pack(year, years[year]) for year in range(first, last + 1)]

    lines = [
        "// @generated by crates/tuvi-core/scripts/gen_lunar_table.py. Do not edit.",
        "// Source: src/refactored/calendar/data/lunar_years.yaml",
        "",
        f"pub(crate) const FIRST_YEAR: i32 = {first};",
        f"pub(crate) const LAST_YEAR: i32 = {last};",
        "",
        "/// One packed word per lunar year. See `calendar::YearInfo` for the layout.",
        f"pub(crate) static LUNAR_YEARS: [u32; {len(words)}] = [",
    ]
    for i in range(0, len(words), 8):
        chunk = ", ".join(f"0x{w:06x}" for w in words[i : i + 8])
        lines.append(f"    {chunk}, // {first + i}")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(words)} years to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
